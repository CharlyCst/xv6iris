#!/usr/bin/env python3
"""Regenerate MachCSL/Platform.lean: the centralized machine/platform
configuration (address layout, hart count, reset vector, IRQ numbers, Sail ISA
extension & counter configuration, PMA regions copied verbatim from the
generated model's `sail_model_init`, and reset PMP configuration)."""
import re

src = open('model/Lean_RV64D/LeanRV64D.lean').read().splitlines()
start = next(i for i, l in enumerate(src) if 'writeReg pma_regions [' in l)
i = start
block = []
while True:
    block.append(src[i])
    if src[i].rstrip().endswith('}]'):
        break
    i += 1
pre = '  writeReg pma_regions '
block[0] = ' ' * len(pre) + block[0][len(pre):]
text = '\n'.join(block)
# the model file's own `open`s, so the literal elaborates as it does there
opens = '\n'.join(l for l in src[:start] if l.startswith('open ') and 'Sail' not in l)

# Parse Sail ISA extension configuration from PlatformConfig.lean (+ Vlen.lean, Xv6Extras.lean)
pcfg = open('model/Lean_RV64D/LeanRV64D/PlatformConfig.lean').read()
vlen_src = open('model/Lean_RV64D/LeanRV64D/Vlen.lean').read()
extras_src = open('model/Lean_RV64D/LeanRV64D/Xv6Extras.lean').read()
sysregs_src = open('model/Lean_RV64D/LeanRV64D/SysRegs.lean').read()

rss_exp = int(re.search(r'def plat_reservation_set_size_exp : Nat := (\d+)', pcfg).group(1))
exp_ext = re.search(
    r'def sys_enable_experimental_extensions \(_ : Unit\) : Bool := (true|false)', extras_src
).group(1) == 'true'
vlevel_name = re.search(r'def vector_support_level : vector_support := (\w+)', vlen_src).group(1)
VLEVELS = {'Disabled': 0, 'Integer': 1, 'Float_single': 2, 'Float_double': 3, 'Full': 4}
vlevel = VLEVELS[vlevel_name]

pcfg_lines = pcfg.splitlines()
hs_start = next(idx for idx, l in enumerate(pcfg_lines) if l.startswith('def hartSupports ('))
arms = []
idx = hs_start + 2
cur = None
while idx < len(pcfg_lines) and pcfg_lines[idx] != '' and not pcfg_lines[idx].startswith(('termination_by', 'decreasing_by')):
    l = pcfg_lines[idx]
    m = re.match(r'^  \| \.(\w+) =>(.*)$', l)
    if m:
        if cur:
            arms.append(cur)
        cur = [m.group(1), m.group(2).strip()]
    elif cur is not None:
        cur[1] += ' ' + l.strip()
    idx += 1
if cur:
    arms.append(cur)

arm_map = dict(arms)
memo = {}


def eval_hs(name):
    if name in memo:
        return memo[name]
    expr = arm_map[name]
    expr = re.sub(r'\(\s*(true|false)\s*:\s*Bool\s*\)', r'\1', expr)
    expr = expr.replace('(sys_enable_experimental_extensions ())', 'True' if exp_ext else 'False')
    expr = expr.replace('plat_reservation_set_size_exp', str(rss_exp))
    expr = expr.replace('xlen', '64')
    expr = re.sub(
        r'\(vector_support_ge vector_support_level (\w+)\)',
        lambda m: 'True' if vlevel >= VLEVELS[m.group(1)] else 'False',
        expr,
    )
    expr = re.sub(
        r'\(hartSupports (\w+)\)',
        lambda m: 'True' if eval_hs(m.group(1)) else 'False',
        expr,
    )
    expr = re.sub(r'if \((.+?) : Bool\) then (.+?) else (.+)', r'(\2 if \1 else \3)', expr)
    expr = expr.replace('≥b', '>=').replace('≤b', '<=')
    expr = expr.replace('&&', ' and ').replace('||', ' or ')
    expr = re.sub(r'\bnot\b', ' not ', expr)
    expr = re.sub(r'\btrue\b', 'True', expr)
    expr = re.sub(r'\bfalse\b', 'False', expr)
    val = bool(eval(expr, {'__builtins__': {}}))
    memo[name] = val
    return val


supported_exts = [name for name, _ in arms if eval_hs(name)]
disabled_exts = [name for name, _ in arms if not eval_hs(name)]


def extract_bv32(defname):
    m = re.search(rf'def {defname} : \(BitVec 32\) := (0b[01]+)#32', sysregs_src)
    val = int(m.group(1), 2)
    return f'0x{val:08X}#32', val


hpm_lit, hpm_val = extract_bv32('sys_writable_hpm_counters')
mctr_lit, mctr_val = extract_bv32('sys_mcounteren_writable_bits')
sctr_lit, sctr_val = extract_bv32('sys_scounteren_writable_bits')

# Compute architectural misa reset value (MXL=2 at bits 63..62 + base I + single-letter A..Z bits)
misa_val = (2 << 62) | (1 << (ord('I') - ord('A')))
for letter in 'ABCDEFGHIJKLMNOPQRSTUVWXYZ':
    ext_name = f'Ext_{letter}'
    if ext_name in arm_map and eval_hs(ext_name):
        misa_val |= 1 << (ord(letter) - ord('A'))
misa_letters = ''.join(
    letter for letter in 'IMAFDCBSUVH'
    if letter == 'I' or (f'Ext_{letter}' in arm_map and eval_hs(f'Ext_{letter}'))
)
misa_lit = f'0x{misa_val:016X}#64'


def fmt_ext_list(names):
    rows = []
    for j in range(0, len(names), 6):
        chunk = ', '.join(f'.{n}' for n in names[j:j + 6])
        rows.append('  ' + chunk)
    return '[\n' + ',\n'.join(rows) + '\n]'


def fmt_ext_doc(names):
    short = [n[4:] if n.startswith('Ext_') else n for n in names]
    lines = []
    for j in range(0, len(short), 10):
        lines.append('  `' + '`, `'.join(short[j:j + 10]) + '`')
    return ',\n'.join(lines)


out = f'''-- AUTO-GENERATED by tools/gen_platform.py from the model's `sail_model_init`, `PlatformConfig`, and `SysRegs`; do not edit.
import MachCSL.SimpAttr
import LeanRV64D.Defs
import LeanRV64D.Xv6Extras

namespace MachCSL
open Sail Sail.ConcurrencyInterfaceV1
open LeanRV64D LeanRV64D.Functions
{opens}

/-! ## Centralized Machine & Platform Configuration

Single source of truth for the platform's physical address layout, hart count,
reset vector, device MMIO windows, interrupt source numbers, Sail ISA extension
and hardware counter configuration, PMA table (extracted from `sail_model_init`
/ `model/sail-config-rv64d.json`), and reset PMP configuration. -/

/-- Number of harts on the platform (`NCPU = 8`, matching `kernel/param.h`). -/
def NCPU : Nat := 8

/-- Architectural reset vector (`KERNBASE = 0x8000_0000`). -/
def resetVector : BitVec 64 := 0x80000000#64

/-- Base physical address of main memory (`KERNBASE = 0x8000_0000`). -/
def ramBase : Nat := 0x80000000

/-- End physical address of main memory (`PHYSTOP = 0x8800_0000`, 128 MiB). -/
def ramEnd : Nat := 0x88000000

/-- Upper bound on device MMIO addresses (`devBound = ramBase`). -/
def devBound : Nat := 0x80000000

/-- CLINT MMIO window `[0x0200_0000, 0x020c_0000)`. -/
def clintBase : Nat := 0x02000000
def clintSize : Nat := 0x000c0000

/-- PLIC MMIO window `[0x0c00_0000, 0x0c40_0000)`. -/
def plicBase : Nat := 0x0c000000
def plicSize : Nat := 0x00400000

/-- UART0 and UART1 MMIO windows (`[0x1000_0000, 0x1000_1000)` and
`[0x1000_a000, 0x1000_b000)`, one 4 KiB page each). -/
def uart0Base : Nat := 0x10000000
def uart1Base : Nat := 0x1000a000
def uartSize  : Nat := 0x00001000

/-- PLIC interrupt source numbers (read off the machine's device tree). -/
def uart0Irq  : Nat := 10
def uart1Irq  : Nat := 12
def virtioIrq : Nat := 1

/-! ### Sail ISA Extensions & Counter Configuration

Extracted from `LeanRV64D.PlatformConfig` (`hartSupports`) and `LeanRV64D.SysRegs`
(kept in sync with `model/sail-config-rv64d.json`):

* **Base ISA & `misa` reset value**: RV64{misa_letters} (`bootMisa = {misa_lit}`).
* **Supported Sail extensions ({len(supported_exts)})**:
{fmt_ext_doc(supported_exts)}.
* **Disabled Sail extensions ({len(disabled_exts)})**:
{fmt_ext_doc(disabled_exts)}.
* **Hardware performance counters (`Zihpm`)**:
  - `Ext_Zihpm = true`, `writableHpmCounters = {hpm_lit}` (`mhpmcounter3..31` and
    `mhpmevent3..31` are implemented as read-only zero; no hardware event counters).
  - `mcounterenWritableBits = {mctr_lit}` and `scounterenWritableBits = {sctr_lit}`
    (only `CY`, `TM`, `IR` bits `[2:0]` are writable; `HPM3..31` bits `[31:3]` are
    read-only zero). -/

/-- Architectural `misa` reset value (`MXL = 2` for RV64, `{misa_letters}` bits set). -/
def bootMisa : BitVec 64 := {misa_lit}

/-- Sail `extension`s enabled on this platform (`hartSupports ext = true`). -/
def supportedExtensions : List extension := {fmt_ext_list(supported_exts)}

/-- Sail `extension`s disabled on this platform (`hartSupports ext = false`). -/
def disabledExtensions : List extension := {fmt_ext_list(disabled_exts)}

/-- Writable HPM counter mask (`sys_writable_hpm_counters` in `LeanRV64D.SysRegs`). -/
def writableHpmCounters : BitVec 32 := {hpm_lit}

/-- Writable `mcounteren` bitmask (`sys_mcounteren_writable_bits` in `LeanRV64D.SysRegs`). -/
def mcounterenWritableBits : BitVec 32 := {mctr_lit}

/-- Writable `scounteren` bitmask (`sys_scounteren_writable_bits` in `LeanRV64D.SysRegs`). -/
def scounterenWritableBits : BitVec 32 := {sctr_lit}

/-- The platform's physical-memory-attribute regions, exactly as the model's
`sail_model_init` installs them from the configuration file. -/
def bootPMA : List PMA_Region :=
{text}

/-- The PMP configuration after the model's `reset_pmp`: every entry has
`A = OFF` and `L = 0` (we take the all-zero configuration). -/
def bootPmpcfg : Vector (BitVec 8) 64 := Vector.replicate 64 0#8

def bootPmpaddr : Vector (BitVec 64) 64 := Vector.replicate 64 0#64

end MachCSL

namespace MachCSL

@[sail_facts] theorem bootPmpcfg_get (i : Nat) : bootPmpcfg[i]! = 0#8 := by
  unfold bootPmpcfg
  by_cases h : i < 64
  · simp [getElem!_pos, h]
  · simp [getElem!_neg, h]; rfl

@[sail_facts] theorem bootPmpaddr_get (i : Nat) : bootPmpaddr[i]! = 0#64 := by
  unfold bootPmpaddr
  by_cases h : i < 64
  · simp [getElem!_pos, h]
  · simp [getElem!_neg, h]; rfl

end MachCSL
'''
open('MachCSL/Platform.lean', 'w').write(out)
